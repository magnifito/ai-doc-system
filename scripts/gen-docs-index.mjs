#!/usr/bin/env node
/**
 * Generates `<docsDir>/INDEX.md` (for humans) and `<docsDir>/index.json` (for
 * agents) from the frontmatter of every document. `kind` is derived from each
 * document's path (docs-taxonomy.mjs), never read from frontmatter.
 *
 * Both outputs are derived. Never hand-edit them; `check-docs.mjs` regenerates
 * them in memory and fails the gate if the committed copies differ.
 *
 * Usage:  node scripts/gen-docs-index.mjs [--check]
 *   --check   write nothing; exit 1 if the committed files are stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parseFrontmatter } from './docs-frontmatter.mjs'
import { DEFAULTS, loadConfig, withDerived } from './docs-config.mjs'
import { isExempt, kindForPath, moduleForPath } from './docs-taxonomy.mjs'
import { listDocs, repoRoot } from './docs-fs.mjs'

export function buildIndex(root, config = loadConfig(root)) {
  const entries = []
  for (const path of listDocs(root, config)) {
    if (isExempt(config, path)) continue
    const { data } = parseFrontmatter(readFileSync(join(root, path), 'utf8'))
    entries.push({
      path,
      title: data.title ?? '',
      kind: kindForPath(config, path) ?? '',
      // Omitted rather than empty when the project declares no modules, so a
      // tree that does not use the axis keeps a byte-identical index.
      ...(moduleForPath(config, path) ? { module: moduleForPath(config, path) } : {}),
      status: data.status ?? '',
      updated: data.updated ?? '',
      ...(data.verified_on ? { verified_on: data.verified_on } : {}),
      ...(data.commitment ? { commitment: data.commitment } : {}),
      ...(Array.isArray(data.changes) && data.changes.length > 0 ? { changes: data.changes } : {}),
      ...(data.implements ? { implements: data.implements } : {}),
      ...(data.code ? { code: data.code } : {}),
      ...(data.superseded_by ? { superseded_by: data.superseded_by } : {}),
    })
  }
  // listDocs is already sorted; keep plain codepoint order (NOT localeCompare,
  // which is ICU/locale-dependent and would break byte-identical regeneration).
  return entries
}

export function renderJson(entries) {
  return `${JSON.stringify({ generated: 'scripts/gen-docs-index.mjs', count: entries.length, docs: entries }, null, 2)}\n`
}

/**
 * Split one tier's entries into `[areaHeading, rows]` pairs. A tier listed in
 * `indexSubdivide` subdivides by the path segment directly under it — files
 * sitting at the tier root land in an unheaded first section. Every other tier
 * stays a single unheaded table.
 */
function groupByArea(config, group, kind) {
  if (!config.indexSubdivide.includes(kind)) return [['', group]]
  const sections = new Map([['', []]])
  const depth = config.docsDir.split('/').length + 1
  for (const entry of group) {
    // When the project groups by module, the area IS the module. Subdividing by
    // the first path segment would produce one heading called `modules` holding
    // every document, which is not an index.
    const rest = entry.path.split('/').slice(depth)
    const area = config.modules.length > 0 ? entry.module ?? '' : rest.length > 1 ? rest[0] : ''
    if (!sections.has(area)) sections.set(area, [])
    sections.get(area).push(entry)
  }
  return [...sections].filter(([, rows]) => rows.length > 0)
}

export function renderMarkdown(entries, config) {
  const resolved = config ?? withDerived(DEFAULTS)
  const out = [
    BANNER,
    '',
    '# Documentation index',
    '',
    `${entries.length} documents. Agents should read \`${resolved.docsDir}/index.json\` instead of this file.`,
    '',
  ]
  const kinds = [...resolved.tierOrder, ...resolved.kinds.filter((k) => !resolved.tierOrder.includes(k))]
  for (const kind of kinds) {
    const group = entries.filter((entry) => entry.kind === kind)
    if (group.length === 0) continue
    out.push(`## ${kind} (${group.length})`, '')
    for (const [area, rows] of groupByArea(resolved, group, kind)) {
      if (area) out.push(`### ${area} (${rows.length})`, '')
      out.push('| Document | Status | Updated |', '|---|---|---|')
      for (const entry of rows) {
        const label = (entry.title || entry.path).replace(/\|/g, '\\|')
        const href = entry.path.slice(resolved.docsDir.length + 1)
        out.push(`| [${label}](${href}) | \`${entry.status}\` | ${entry.updated} |`)
      }
      out.push('')
    }
  }
  const unknown = entries.filter((entry) => !resolved.kinds.includes(entry.kind))
  if (unknown.length > 0) {
    out.push('## unclassified', '', ...unknown.map((entry) => `- ${entry.path}`), '')
  }
  return out.join('\n')
}

// The invocation in the banner is runner-agnostic on purpose: host projects
// wire the script under npm, pnpm or bun scripts, but `node` is always true.
const BANNER = '<!-- GENERATED by scripts/gen-docs-index.mjs. Do not edit. Run `node scripts/gen-docs-index.mjs`. -->'

/** Markdown link target from a file in `fromDir` to a repo-relative `target`. */
function linkTo(fromDir, target) {
  return target.startsWith(`${fromDir}/`) ? target.slice(fromDir.length + 1) : target
}

/**
 * One module's register: what the module is, what is true about it today, and
 * what is outstanding. Generated, because a hand-written register drifts from
 * the frontmatter it summarises — which is how the roadmap this replaces went
 * six months stale.
 */
export function renderModuleReadme(config, moduleDef, entries) {
  const dir = `${config.docsDir}/${config.moduleRoot}${moduleDef.key}`
  const mine = entries.filter((entry) => entry.module === moduleDef.key)
  const out = [BANNER, '', `# ${moduleDef.key}`, '']

  const requires = moduleDef.requires?.length
    ? ` · requires ${moduleDef.requires.map((key) => `\`${key}\``).join(' or ')}`
    : ''
  out.push(`Class: \`${moduleDef.class}\`${requires}`, '')

  const state = mine.filter((entry) => entry.kind === 'state')
  out.push('## Reflection — what this module is today', '')
  if (state.length === 0) out.push('_No reflection document yet. This module has not been audited._', '')
  else {
    out.push('| Document | Verified | Updated |', '|---|---|---|')
    for (const entry of state) {
      out.push(`| [${entry.title || entry.path}](${linkTo(dir, entry.path)}) | ${entry.verified_on || '—'} | ${entry.updated} |`)
    }
    out.push('')
  }

  const todo = mine.filter((entry) => entry.kind === 'todo')
  out.push('## Wishlist — what is outstanding', '')
  if (todo.length === 0) out.push('_Nothing outstanding._', '')
  else {
    for (const commitment of ['committed', 'optional']) {
      const rows = todo.filter((entry) => (entry.commitment || 'committed') === commitment)
      if (rows.length === 0) continue
      out.push(`### ${commitment} (${rows.length})`, '', '| Document | Updated |', '|---|---|')
      for (const entry of rows) out.push(`| [${entry.title || entry.path}](${linkTo(dir, entry.path)}) | ${entry.updated} |`)
      out.push('')
    }
  }

  const reference = mine.filter((entry) => entry.kind === 'reference')
  if (reference.length > 0) {
    out.push(
      `## Reference (${reference.length})`,
      '',
      'Competitor-derived. Not a commitment, never a build spec.',
      '',
    )
  }
  return out.join('\n')
}

/**
 * The cross-module wishlist. Committed before optional, because the reader's
 * question is "what have we promised", and the optional half is noise until
 * that is answered.
 */
export function renderRoadmap(config, entries) {
  const todo = entries.filter((entry) => entry.kind === 'todo')
  const out = [
    BANNER,
    '',
    '# Roadmap',
    '',
    `${todo.length} outstanding items across ${config.modules.length} modules.`,
    '',
  ]
  for (const commitment of ['committed', 'optional']) {
    const rows = todo.filter((entry) => (entry.commitment || 'committed') === commitment)
    if (rows.length === 0) continue
    out.push(`## ${commitment} (${rows.length})`, '', '| Module | Item | Changes | Updated |', '|---|---|---|---|')
    for (const entry of rows) {
      const link = entry.path.slice(config.docsDir.length + 1)
      out.push(`| \`${entry.module}\` | [${entry.title || entry.path}](${link}) | ${entry.changes?.length ?? 0} | ${entry.updated} |`)
    }
    out.push('')
  }
  return out.join('\n')
}

/** Every generated artefact, as `[repoRelativePath, content]` pairs. */
export function renderIndex(root, config = loadConfig(root)) {
  const entries = buildIndex(root, config)
  const targets = [
    [`${config.docsDir}/index.json`, renderJson(entries)],
    [`${config.docsDir}/INDEX.md`, renderMarkdown(entries, config)],
  ]
  for (const moduleDef of config.modules) {
    targets.push([
      `${config.docsDir}/${config.moduleRoot}${moduleDef.key}/README.md`,
      renderModuleReadme(config, moduleDef, entries),
    ])
  }
  if (config.modules.length > 0) {
    targets.push([`${config.docsDir}/ROADMAP.md`, renderRoadmap(config, entries)])
  }
  return targets
}

function main() {
  const root = repoRoot()
  const config = loadConfig(root)
  const targets = renderIndex(root, config)
  const check = process.argv.includes('--check')

  let stale = false
  for (const [path, content] of targets) {
    if (check) {
      let current = null
      try {
        current = readFileSync(join(root, path), 'utf8')
      } catch {
        /* missing counts as stale */
      }
      if (current !== content) {
        console.error(`stale: ${path} — run \`node scripts/gen-docs-index.mjs\``)
        stale = true
      }
    } else {
      writeFileSync(join(root, path), content)
      console.log(`wrote ${path}`)
    }
  }
  process.exit(stale ? 1 : 0)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
